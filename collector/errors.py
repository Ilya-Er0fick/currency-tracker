"""Виды отказов внешних источников.

От вида зависит реакция: временный отказ повторяется, остальные нет.
Любой из них засчитывается источнику как неуспешная попытка.
"""


class SourceError(Exception):
    """Источник не дал пригодного ответа."""


class TransientError(SourceError):
    """Таймаут, разрыв соединения, 429 или 5xx: есть смысл повторить."""


class InvalidResponseError(SourceError):
    """Ответ получен, но разобрать его нельзя."""


class RequestRejectedError(SourceError):
    """Источник отклонил запрос (4xx): ошибка в запросе, повтор не поможет."""
